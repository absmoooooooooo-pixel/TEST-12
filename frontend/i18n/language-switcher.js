/* ==================================================
   LANGUAGE SWITCHER BEHAVIOUR
   The English site is the default and always stays in English.
   Choosing another language navigates to that language's own
   pre-rendered page tree. The in-place translation runtime is
   intentionally not driven by these links.

   Every menu entry already carries the correct URL, generated from
   the page's own <link rel="alternate" hreflang="..."> set by
   tools/fix_language_links.py, so navigation works with JavaScript
   disabled and from any URL shape (with or without a trailing slash,
   with or without index.html). This script only closes the menu,
   keeps the English page English, and repairs a placeholder href if
   one is ever left behind.
 ================================================== */
(function () {
    "use strict";

    var switcher = document.querySelector(".lang-switch");
    if (!switcher) {
        return;
    }

    var links = Array.prototype.slice.call(switcher.querySelectorAll(".lang-switch__menu a"));

    /* Never let a stored choice translate an English URL on load. */
    try {
        if (localStorage.getItem("mw-lang") !== "en") {
            localStorage.setItem("mw-lang", "en");
        }
        if (sessionStorage.getItem("mw-lang") !== "en") {
            sessionStorage.setItem("mw-lang", "en");
        }
    } catch (error) {
        /* Storage can be unavailable in private browsing. */
    }

    function close() {
        switcher.removeAttribute("open");
    }

    /* The page's hreflang alternates describe its exact counterpart in every
       language. They are the authority; nothing is inferred from the URL. */
    function alternatePaths() {
        var map = {};
        var tags = document.querySelectorAll('link[rel="alternate"][hreflang]');
        Array.prototype.forEach.call(tags, function (tag) {
            var code = (tag.getAttribute("hreflang") || "").trim();
            var href = (tag.getAttribute("href") || "").trim();
            if (!code || !href || code.toLowerCase() === "x-default") {
                return;
            }
            try {
                map[code] = new URL(href, location.href).pathname;
            } catch (error) {
                /* Ignore an unparsable alternate. */
            }
        });
        return map;
    }

    /* When the whole site is served from a sub-directory, the alternates are
       still written for the domain root. The current page identifies the
       prefix to prepend so the target stays inside the same deployment. */
    function sitePrefix(map) {
        var current = (document.documentElement.getAttribute("lang") || "en").trim();
        var own = map[current];
        if (!own) {
            return "";
        }
        var here = (location.pathname || "/").replace(/index\.html$/, "");
        var wanted = own.replace(/index\.html$/, "");
        if (!wanted) {
            return "";
        }
        var at = here.lastIndexOf(wanted);
        if (at > 0) {
            return here.slice(0, at);
        }
        return "";
    }

    /* A clean URL such as /es/calculators/plate/ only opens the page when the
       server resolves a folder to its index.html. Opened from disk, or by any
       host without that rule, the same URL shows a folder listing. Every link
       therefore names the HTML file itself. */
    function filePath(target) {
        if (!target) {
            return target;
        }
        if (/\/$/.test(target)) {
            return target + "index.html";
        }
        if (/\.[a-z0-9]+$/i.test(target)) {
            return target;
        }
        return target + "/index.html";
    }

    /* Safety net only: a placeholder href is replaced with the correct page
       from the alternates. A working href is never rewritten, so a layout
       generated by the site build is always used as-is. */
    var map = null;
    var prefix = null;

    links.forEach(function (link) {
        var code = link.getAttribute("hreflang");
        var href = (link.getAttribute("href") || "").trim();

        if (code && (href === "" || href === "#")) {
            if (map === null) {
                map = alternatePaths();
                prefix = sitePrefix(map);
            }
            /* No alternate for this language: open that language's home page
               instead of leaving a dead link. */
            var target = map[code] || (code === "en" ? "/" : "/" + code + "/");
            link.setAttribute("href", prefix + filePath(target));
        }

        /* No preventDefault: the switcher entries are ordinary navigation
           links to the pre-created language pages. */
        link.addEventListener("click", close);
    });

    document.addEventListener("click", function (event) {
        if (!switcher.open) {
            return;
        }
        if (!switcher.contains(event.target)) {
            close();
        }
    });

    document.addEventListener("keydown", function (event) {
        if (event.key === "Escape") {
            close();
        }
    });
})();
