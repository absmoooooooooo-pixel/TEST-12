def rename_keys(data: dict, old: str, new: str) -> int:
    changed = 0
    for section in ("text", "attrs"):
        block = data.get(section)
        if not isinstance(block, dict):
            continue
        renamed = {}
        for key, value in block.items():
            if old in key:
                renamed[key.replace(old, new)] = value
                changed += 1
            else:
                renamed[key] = value
        data[section] = renamed
    return changed


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()

    totals = 0
    misses: list[tuple[str, str]] = []

    jobs: list[tuple[str, Path, str, str]] = []
    for lang, page, old, new in ENTRIES:
        if page == "*":
            jobs.extend((lang, path, old, new) for path in sorted((ROOT / lang).glob("**/index.html")))
        else:
            jobs.append((lang, ROOT / lang / page, old, new))

    for lang, path, old, new in jobs:
        if not path.exists():
            misses.append((lang, path.as_posix(), old[:40]))
            continue
        with path.open("r", encoding="utf-8", newline="") as handle:
            source = handle.read()

        match = MAP.search(source)
        if match:
            try:
                data = json.loads(match.group(2))
            except json.JSONDecodeError:
                data = None
        else:
            data = None

        hits = source.count(old)
        key_hits = rename_keys(data, old, new) if data else 0
        if hits == 0 and key_hits == 0:
            misses.append((lang, path.as_posix(), old[:40]))
            continue

        if args.write:
            body = MAP.sub(lambda m: m.group(1) + "__MAP__" + m.group(3), source)
            body = body.replace(old, new)
            if data is not None:
                payload = json.dumps(data, ensure_ascii=False, separators=(",", ":")).replace(
                    "</", "<\\/"
                )
                body = body.replace("__MAP__", payload)
            with path.open("w", encoding="utf-8", newline="") as handle:
                handle.write(body)
        totals += 1

    action = "updated" if args.write else "would update"
    print(f"{action}: {totals} entry/entries")
    for lang, page, preview in misses:
        print(f"  no match: {page}  {preview}")

    term_hits = 0
    term_misses: list[str] = []
    for lang, old, new in TERMS:
        guard = re.compile(r"(?<![\u0900-\u097f])" + re.escape(old))
        lang_hits = 0
        for path in sorted((ROOT / lang).glob("**/index.html")):
            with path.open("r", encoding="utf-8", newline="") as handle:
                source = handle.read()
            match = MAP.search(source)
            data = None
            if match:
                try:
                    data = json.loads(match.group(2))
                except json.JSONDecodeError:
                    data = None
            body = MAP.sub(lambda m: m.group(1) + "__MAP__" + m.group(3), source)
            replaced = guard.sub(new, body)
            if data is not None:
                for section in ("text", "attrs"):
                    block = data.get(section)
                    if isinstance(block, dict):
                        data[section] = {
                            guard.sub(new, key): value for key, value in block.items()
                        }
                replaced = replaced.replace(
                    "__MAP__",
                    json.dumps(data, ensure_ascii=False, separators=(",", ":")).replace(
                        "</", "<\\/"
                    ),
                )
            else:
                replaced = replaced.replace("__MAP__", match.group(2) if match else "")
            if replaced != source:
                lang_hits += body.count(old) + (0 if data is None else 0)
                if args.write:
                    with path.open("w", encoding="utf-8", newline="") as handle:
                        handle.write(replaced)
        if lang_hits == 0:
            term_misses.append(f"{lang}: {old}")
        term_hits += lang_hits

    print(f"term replacements: {term_hits}")
    for preview in term_misses:
        print(f"  term no match: {preview}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
