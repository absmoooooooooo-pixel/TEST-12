def main() -> int:
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except AttributeError:
        pass

    changed = 0
    for code in language_codes():
        dictionary = load_dictionary(code)
        strings = dictionary.setdefault("strings", {})
        for key, values in MORE.items():
            value = key if code == EN else values[code]
            if strings.get(key) != value:
                strings[key] = value
                changed += 1
        dictionary_path(code).write_text(
            json.dumps(dictionary, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
    print(f"corrected {changed} mixed-language strings across {len(language_codes())} dictionaries")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
